#!/usr/bin/env bash
# mu-vm-provision - run INSIDE a freshly-cloned worker VM (as root) to turn it into a live worker: mount the
# burn disk, install docker + tailscale, join the tailnet, clone the repo, point the worker's /data churn at
# THIS VM's own folder on the burn disk, and bring the stack up.
#
#   sudo WORKER_TOKEN=xxxx TS_AUTHKEY=tskey-auth-xxxx MAIN_URL=http://100.67.109.13:8080 bash mu-vm-provision.sh
#
# Each VM has its own burn disk (isolated already); the per-VM folder below is belt-and-suspenders so workers
# can never touch each other's files even if the burn storage is ever shared.
set -euo pipefail

: "${WORKER_TOKEN:?set WORKER_TOKEN to the shared worker secret}"
: "${TS_AUTHKEY:?set TS_AUTHKEY (https://login.tailscale.com/admin/settings/keys - reusable, ephemeral off)}"
MAIN_URL="${MAIN_URL:-http://100.67.109.13:8080}"
REPO="${REPO:-https://github.com/NAKE-1/manga-utils.git}"
GITDIR=/root/manga-src

# --- 1. find + mount the burn disk (download churn only) ------------------------------------------
echo "== disks (verify the burn disk below is the blank data disk, NOT the OS disk) =="
lsblk -o NAME,SIZE,TYPE,FSTYPE,MOUNTPOINT
ROOTDISK=$(lsblk -no pkname "$(findmnt -no SOURCE /)" | head -1)
BURN_DEV="${BURN_DEV:-}"
if [ -z "$BURN_DEV" ]; then                       # auto-pick the whole disk that isn't the OS disk and has no partitions
  for d in $(lsblk -dpno NAME,TYPE | awk '$2=="disk"{print $1}'); do
    base=$(basename "$d")
    [ "$base" = "$ROOTDISK" ] && continue
    lsblk -no NAME "$d" | grep -q "${base}." && continue   # skip anything with child partitions
    BURN_DEV="$d"; break
  done
fi
[ -n "$BURN_DEV" ] || { echo "could not auto-pick a blank burn disk - set BURN_DEV=/dev/sdX and re-run"; exit 1; }
echo ">> burn disk = $BURN_DEV  (OS disk = /dev/$ROOTDISK). Formatting ONLY if it has no filesystem."
blkid "$BURN_DEV" >/dev/null 2>&1 || mkfs.ext4 -L muburn "$BURN_DEV"   # never reformats a disk that already has data
mkdir -p /mnt/burn
grep -q 'LABEL=muburn' /etc/fstab || echo 'LABEL=muburn /mnt/burn ext4 defaults,nofail 0 2' >> /etc/fstab
mount -a
BURNDIR="/mnt/burn/$(hostname)"                   # PER-VM folder: workers never share files
mkdir -p "$BURNDIR/worker-data"

# --- 2. docker + tailscale ------------------------------------------------------------------------
command -v docker >/dev/null || curl -fsSL https://get.docker.com | sh
command -v tailscale >/dev/null || curl -fsSL https://tailscale.com/install.sh | sh
tailscale up --authkey="$TS_AUTHKEY" --accept-dns=false --hostname="$(hostname)"

# --- 3. repo + burn-bind override -----------------------------------------------------------------
[ -d "$GITDIR/.git" ] || git clone "$REPO" "$GITDIR"
cd "$GITDIR" && git pull --ff-only || true
cat > "$GITDIR/deploy/worker/docker-compose.override.yml" <<YML
# Per-VM burn-drive bind (generated by mu-vm-provision.sh, do NOT commit): the worker's /data (library + temp
# download churn) lives in this VM's own folder on the burn SSD, off the boot disk and isolated per worker.
volumes:
  mu-worker-data:
    driver: local
    driver_opts:
      type: none
      o: bind
      device: $BURNDIR/worker-data
YML

# --- 4. bring the worker up -----------------------------------------------------------------------
cd "$GITDIR/deploy/worker"
WORKER_TOKEN="$WORKER_TOKEN" MAIN_URL="$MAIN_URL" docker compose up -d --build
echo "done. In the main UI add worker: http://$(tailscale ip -4 | head -1):8790  (token $WORKER_TOKEN), then set Exit node = Auto."
